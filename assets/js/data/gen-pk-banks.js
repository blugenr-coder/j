/* Picture banks for the pre-K skills that are not systematic.

   "Recognize uppercase letter M" needs no bank: the letter is the content. But
   "Match baby animals to parents" is nothing without the animals, and
   "Butterfly life cycle" is nothing without the four stages in order. This file
   holds those, each as pictures a child can read without reading.

   Five shapes cover almost all of them:
     seq     an ordered list of steps          → put these in order
     split   two labelled groups of pictures   → sort them
     pairs   two things that belong together   → draw the line
     set     one labelled group of pictures    → find, count, name, colour
     opp     a pair of opposites               → which one is X
*/

const seq = (id, name, area, steps) => ({ id, name, area, kind: 'sequence', steps });
const split = (id, name, area, a, b) => ({ id, name, area, kind: 'binarySort', groups: [a, b] });
const pairs = (id, name, area, items) => ({ id, name, area, kind: 'pairs', items });
const set = (id, name, area, items, noun) => ({ id, name, area, kind: 'pickSet', items, noun });
const opp = (id, name, area, a, b) => ({ id, name, area, kind: 'opposites', a, b });

