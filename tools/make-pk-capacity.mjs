/* Measures how many distinct questions each preschool skill and format can
   actually put on one sheet, and writes the answer to
   assets/js/data/gen-pk-capacity.js.

   This has to be measured per skill, not per kind. The -at rhyme family has
   nine words and the -it family has three, so "rhyme, sorted into two boxes"
   fills a ten-question sheet for one and runs dry at six for the other.
   Measuring one rhyme skill and applying the answer to all twelve is how a
   worksheet card ends up promising ten questions and delivering six.

   Measuring all two thousand combinations takes two seconds, which is fine
   here and far too slow to repeat on every page load, so the result is a
   generated file. tools/check-preschool.mjs re-measures a sample on every run
   and fails if this file has drifted, so it cannot quietly go stale.

   Run: node tools/make-pk-capacity.mjs                                      */

import { writeFileSync } from 'node:fs';
import { PK_SKILLS } from '../assets/js/data/gen-pk-skills.js';
import { PK_THEMES } from '../assets/js/data/gen-pk-themes.js';
import { contentFor } from '../assets/js/data/gen-pk-content.js';
import { questionFor } from '../assets/js/data/gen-pk-formats.js';
import { build, seedFrom } from '../assets/js/data/gen-core.js';

/* No shape in the catalogue asks for more than twenty-eight, so there is
   nothing to learn by probing deeper. */
export const CEILING = 28;
/* Three themes and take the worst. A family has to keep its promise on every
   theme it wears, not on the luckiest one. */
const THEMES_TRIED = 3;

export function measure(skill, format) {
  let worst = CEILING;
  for (let t = 0; t < THEMES_TRIED; t++) {
    const theme = PK_THEMES[(seedFrom(skill.id + format) + t * 17) % PK_THEMES.length];
    const maker = r => questionFor(format, contentFor(skill, theme, PK_THEMES, r), { r, level: 1 });
    let n = 0;
    try { n = build(seedFrom(skill.id + format + t), CEILING, [maker]).length; } catch { n = 0; }
    if (n < worst) worst = n;
  }
  return worst;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const lean = [];
  let total = 0;
  for (const skill of PK_SKILLS) {
    for (const format of skill.formats) {
      total++;
      const n = measure(skill, format);
      if (n < CEILING) lean.push([`${skill.id}|${format}`, n]);
    }
  }
  lean.sort((a, b) => a[0].localeCompare(b[0]));

  const rows = lean.map(([k, n]) => `  '${k}': ${n}`).join(',\n');
  const out = `/* GENERATED by tools/make-pk-capacity.mjs — do not edit by hand.

   How many distinct questions each preschool skill can put on one sheet in
   each of its formats, measured across three themes and recorded at the worst
   of them. A family has to keep its promise on every theme it wears.

   Only the lean ones are listed. Anything missing reached the ${CEILING}-question
   ceiling the probe stops at, which is more than any worksheet in the
   catalogue asks for.

   ${total} skill-and-format pairs measured; ${lean.length} of them run out before ${CEILING}.
   tools/check-preschool.mjs re-measures a sample on every run, so this cannot
   go stale without a check failing.                                          */

export const PK_CEILING = ${CEILING};

export const PK_CAPACITY = {
${rows}
};
`;
  writeFileSync(new URL('../assets/js/data/gen-pk-capacity.js', import.meta.url), out);
  console.log(`measured ${total} pairs; ${lean.length} below the ${CEILING} ceiling`);
  console.log('wrote assets/js/data/gen-pk-capacity.js');
}
