/* Extract every translatable content string for one subject.

   The worksheet content — terms, definitions, true and false statements,
   scenarios — lives in the unit banks, not in the markup, so it cannot be
   found by walking a page. This pulls it straight out of the units and writes
   a stub pack with every string mapped to itself, ready to be translated.

     node tools/make-content-pack.mjs science es

   Run again after adding units and it keeps the translations already there,
   adding only what is new. That matters: this is a job done over many
   sittings, and a tool that discards finished work each time is a tool nobody
   uses twice.
*/

import { writeFileSync, existsSync } from 'node:fs';
import { UNITS } from '../assets/js/data/units.js';
import { SUBJECTS } from '../assets/js/data/catalog.js';

const [subjectId, lang] = process.argv.slice(2);
const subject = SUBJECTS.find(s => s.id === subjectId);
if (!subject || !lang) {
  console.error('Usage: node tools/make-content-pack.mjs <subject-id> <lang>');
  console.error('Subjects: ' + SUBJECTS.map(s => s.id).join(', '));
  process.exit(1);
}

const topics = new Set(subject.topics.map(t => t.id));
const strings = new Set();

for (const [topic, units] of Object.entries(UNITS)) {
  if (!topics.has(topic)) continue;
  for (const u of units) {
    strings.add(u.name);
    for (const [term, meaning] of u.facts ?? []) { strings.add(term); strings.add(meaning); }
    for (const s of u.truths ?? []) strings.add(s);
    for (const s of u.myths ?? []) strings.add(s);
    for (const [label, steps] of u.sequences ?? []) {
      strings.add(label);
      for (const step of steps) strings.add(step);
    }
    for (const [scenario, answer] of u.applications ?? []) {
      strings.add(scenario); strings.add(answer);
    }
  }
}

const path = `assets/js/i18n/content/${lang}/${subjectId}.js`;
let existing = {};
if (existsSync(path)) {
  existing = (await import(`../${path}`)).DICT ?? {};
}

const sorted = [...strings].filter(Boolean).sort();
const done = sorted.filter(s => existing[s] && existing[s] !== s).length;

const body = sorted.map(s => {
  const value = existing[s] ?? s;
  return `  ${JSON.stringify(s)}: ${JSON.stringify(value)},`;
}).join('\n');

writeFileSync(path, `/* ${subject.name} — worksheet content in ${lang}.
   Generated by tools/make-content-pack.mjs and then translated by hand. A
   string mapped to itself is one still waiting; the coverage check counts
   those as untranslated, so the number cannot be inflated by the stub. */

export const DICT = {
${body}
};
`);

console.log(`${path}`);
console.log(`  ${sorted.length} strings, ${done} already translated, ${sorted.length - done} to go`);
